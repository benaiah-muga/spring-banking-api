ALTER TABLE accounts
    ADD CONSTRAINT uk_accounts_id_user UNIQUE (id, user_id);

CREATE TABLE payment_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    source_account_id BIGINT NOT NULL,
    erp_system VARCHAR(64) NOT NULL,
    erp_payment_reference VARCHAR(128) NOT NULL,
    invoice_reference VARCHAR(128),
    beneficiary_name VARCHAR(150) NOT NULL,
    beneficiary_account VARCHAR(128) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    transaction_reference VARCHAR(36),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_payment_orders_user
        FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_payment_orders_account_owner
        FOREIGN KEY (source_account_id, user_id) REFERENCES accounts(id, user_id),
    CONSTRAINT fk_payment_orders_transaction
        FOREIGN KEY (transaction_reference) REFERENCES transactions(reference_number),
    CONSTRAINT uk_payment_orders_user_erp_reference
        UNIQUE (user_id, erp_system, erp_payment_reference),
    CONSTRAINT uk_payment_orders_transaction_reference
        UNIQUE (transaction_reference),
    CONSTRAINT chk_payment_orders_amount_positive CHECK (amount > 0),
    CONSTRAINT chk_payment_orders_currency CHECK (currency = 'USD'),
    CONSTRAINT chk_payment_orders_status CHECK (status IN ('PENDING', 'PROCESSING', 'SETTLED', 'REJECTED')),
    CONSTRAINT chk_payment_orders_required_text CHECK (
        length(trim(erp_system)) > 0
        AND length(trim(erp_payment_reference)) > 0
        AND length(trim(beneficiary_name)) > 0
        AND length(trim(beneficiary_account)) > 0
    ),
    CONSTRAINT chk_payment_orders_settlement_reference CHECK (
        (status = 'SETTLED' AND transaction_reference IS NOT NULL)
        OR (status <> 'SETTLED' AND transaction_reference IS NULL)
    )
);

CREATE INDEX idx_payment_orders_user_created ON payment_orders(user_id, created_at DESC);
CREATE INDEX idx_payment_orders_account_created ON payment_orders(source_account_id, created_at DESC);
